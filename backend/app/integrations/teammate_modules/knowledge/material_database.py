def get_material_profile(material_name: str) -> Optional[MaterialEnvironmentalProfile]:
    """Retrieve environmental profile for a normalized material key."""
    key = material_name.strip().lower().replace(" ", "_").replace("-", "_")
    data = MATERIAL_KNOWLEDGE_BASE.get(key)
    if not data:
        return None

    return MaterialEnvironmentalProfile(
        material=key,
        water_liters_per_kg=data["water_liters_per_kg"],
        co2_kg_per_kg=data["co2_kg_per_kg"],
        energy_mj_per_kg=data["energy_mj_per_kg"],
        chemicals_intensity=data["chemicals_intensity"],
        microplastic_shedding_risk=data["microplastic_shedding_risk"],
        biodegradability=data["biodegradability"],
        source_reference=data["source_reference"],
        custom_indicators={
            "display_name": data["display_name"],
            "fiber_type": data["fiber_type"],
            "provenance": data["provenance"],
            "pros": data["pros"],
            "cons": data["cons"],
        },
    )


def get_batch_material_profiles(materials: List[str]) -> Dict[str, MaterialEnvironmentalProfile]:
    """Retrieve environmental profiles for a list of material keys."""
    profiles: Dict[str, MaterialEnvironmentalProfile] = {}
    for mat in materials:
        profile = get_material_profile(mat)
        if profile:
            profiles[profile.material] = profile
    return profiles


def list_supported_materials() -> List[str]:
    """List all material keys supported in the Knowledge Base."""
    return sorted(list(MATERIAL_KNOWLEDGE_BASE.keys()))
